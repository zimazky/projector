import { test, expect } from './fixtures'
import type { Page } from '@playwright/test'

async function create(page: Page) {
	await page.goto('/index.html')
	await page.getByRole('button', { name: 'Создать новый документ', exact: true }).click()
}

async function projects(page: Page) {
	await create(page)
	await page.getByRole('button', { name: 'Меню', exact: true }).click()
	const command = page
		.getByRole('dialog', { name: 'Меню', exact: true })
		.getByRole('button', { name: 'Projects', exact: true })
	await command.focus()
	await command.press('Enter')
}

async function eventEditor(page: Page) {
	await page.clock.setFixedTime(new Date('2026-11-01T12:00:00Z'))
	await create(page)
	const input = page.getByRole('textbox', { name: 'Новое событие: 2026.11.01', exact: true })
	await input.focus()
	await page.keyboard.insertText('Keyboard event')
	await page.keyboard.press('Enter')
	await expect(page.getByRole('dialog', { name: 'Редактор события', exact: true })).toBeVisible()
	await page.getByRole('button', { name: 'Add Event', exact: true }).focus()
	await page.keyboard.press('Enter')
	const event = page.locator('[data-date="2026.11.01"] [draggable="true"]').filter({ hasText: 'Keyboard event' })
	await event.focus()
	await page.keyboard.press('Enter')
	return event
}

test('клавиатура: меню удерживает Tab, блокирует фон, Escape возвращает фокус', async ({ page }) => {
	await page.goto('/index.html')
	const trigger = page.getByRole('button', { name: 'Меню', exact: true })
	await page.keyboard.press('Tab')
	await expect(trigger).toBeFocused()
	await page.keyboard.press('Enter')
	const menu = page.getByRole('dialog', { name: 'Меню', exact: true })
	await expect(menu).toHaveAttribute('aria-modal', 'true')
	await expect(menu.getByRole('button', { name: 'Войти', exact: true })).toBeFocused()
	await page.keyboard.press('Shift+Tab')
	await expect(menu.getByRole('button', { name: 'Закрыть меню', exact: true })).toBeFocused()
	await page.keyboard.press('Tab')
	await expect(menu.getByRole('button', { name: 'Войти', exact: true })).toBeFocused()
	await trigger.evaluate(element => element.focus())
	await expect(menu.getByRole('button', { name: 'Войти', exact: true })).toBeFocused()
	await page.keyboard.press('Escape')
	await expect(menu).toHaveCount(0)
	await expect(trigger).toBeFocused()
	await page.keyboard.press('Enter')
	await page.keyboard.press('Escape')
	await page.keyboard.press('Enter')
	await expect(menu).toBeVisible()
	await menu.getByRole('button', { name: 'Новый документ', exact: true }).focus()
	await page.keyboard.press('Space')
	await expect(menu).toHaveCount(0)
	await expect(page.getByTestId('document-tab')).toHaveCount(1)
})

test('клавиатура: создание проекта через Tab и Enter, возврат фокуса', async ({ page }) => {
	await projects(page)
	const trigger = page.getByRole('button', { name: 'Add Project', exact: true })
	await trigger.focus()
	await page.keyboard.press('Enter')
	const form = page.getByRole('dialog', { name: 'Add Project', exact: true })
	await expect(form.getByLabel('Project Name', { exact: true })).toBeFocused()
	await page.keyboard.insertText('Keyboard project')
	for (let i = 0; i < 5; i++) await page.keyboard.press('Tab')
	await expect(form.getByRole('button', { name: 'Add', exact: true })).toBeFocused()
	await page.keyboard.press('Enter')
	await expect(form).toHaveCount(0)
	await expect(trigger).toBeFocused()
	await expect(page.getByText('Keyboard project', { exact: true })).toBeVisible()
	await expect(page.getByTitle('Delete Default', { exact: true })).toBeDisabled()
})

test('вложенная палитра: выбор цвета, удержание фокуса и Escape только верхнего окна', async ({ page }, info) => {
	await projects(page)
	const add = page.getByRole('button', { name: 'Add Project', exact: true })
	await add.click()
	const parent = page.locator('dialog[aria-label="Add Project"]')
	const trigger = parent.getByRole('button', { name: 'Палитра: Text Color', exact: true })
	await trigger.focus()
	await page.keyboard.press('Enter')
	const palette = page.getByRole('dialog', { name: 'Палитра: Text Color', exact: true })
	await expect(palette).toBeVisible()
	const color = palette.getByRole('button', { name: 'Выбрать цвет #F44336', exact: true })
	await color.focus()
	await page.keyboard.press('Space')
	await expect(parent.getByLabel('Text Color', { exact: true })).toHaveValue('#F44336')
	await palette.getByRole('button', { name: 'Закрыть палитру', exact: true }).focus()
	await page.keyboard.press('Tab')
	await expect(palette.locator(':focus')).toHaveCount(1)
	await parent.getByLabel('Project Name').evaluate(element => element.focus())
	await expect(palette.locator(':focus')).toHaveCount(1)
	await palette.evaluate(async element => {
		await Promise.all(element.getAnimations().map(animation => animation.finished))
	})
	await page.screenshot({ path: info.outputPath('nested-palette.png'), fullPage: true })
	await page.keyboard.press('Escape')
	await expect(palette).toHaveCount(0)
	await expect(trigger).toBeFocused()
	await expect(parent).toBeVisible()
	await page.keyboard.press('Escape')
	await expect(parent).toHaveCount(0)
	await expect(add).toBeFocused()
})

test('вложенный выбор даты: Tab остаётся в окне, Escape возвращает к полю события', async ({ page }) => {
	await eventEditor(page)
	const editor = page.locator('dialog[aria-label="Редактор события"]')
	const trigger = editor.getByRole('button', { name: 'Выбрать дату: Start date', exact: true })
	await trigger.focus()
	await page.keyboard.press('Enter')
	const picker = page.getByRole('dialog', { name: 'Выбор даты: Start date', exact: true })
	await expect(picker).toBeVisible()
	await picker.getByRole('button', { name: 'Ok', exact: true }).focus()
	await page.keyboard.press('Tab')
	await expect(picker.locator(':focus')).toHaveCount(1)
	await page.keyboard.press('Escape')
	await expect(picker).toHaveCount(0)
	await expect(trigger).toBeFocused()
	await expect(editor).toBeVisible()
	await page.keyboard.press('Escape')
	await expect(editor).toHaveCount(0)
})

test('вложенное удаление события: начальный фокус на отмене, Escape не удаляет событие', async ({ page }) => {
	const event = await eventEditor(page)
	const editor = page.locator('dialog[aria-label="Редактор события"]')
	const remove = editor.getByRole('button', { name: 'Delete', exact: true })
	await remove.focus()
	await page.keyboard.press('Enter')
	const confirmation = page.getByRole('dialog', { name: 'Подтверждение действия', exact: true })
	await expect(confirmation.getByRole('button', { name: 'Cancel', exact: true })).toBeFocused()
	await page.keyboard.press('Shift+Tab')
	await expect(confirmation.getByRole('button', { name: 'Yes', exact: true })).toBeFocused()
	await page.keyboard.press('Tab')
	await expect(confirmation.getByRole('button', { name: 'Cancel', exact: true })).toBeFocused()
	await page.keyboard.press('Escape')
	await expect(confirmation).toHaveCount(0)
	await expect(remove).toBeFocused()
	await expect(editor).toBeVisible()
	await page.keyboard.press('Escape')
	await expect(editor).toHaveCount(0)
	await expect(event).toBeVisible()
})

test('закрытие документа: Escape означает отмену и возвращает фокус на крестик', async ({ page }) => {
	await projects(page)
	await page.getByRole('button', { name: 'Add Project', exact: true }).click()
	await page.getByLabel('Project Name', { exact: true }).fill('Unsaved')
	await page.getByRole('button', { name: 'Add', exact: true }).click()
	const close = page.getByTitle('Закрыть вкладку', { exact: true })
	await close.focus()
	await page.keyboard.press('Enter')
	const confirmation = page.getByRole('dialog', { name: 'Сохранение изменений перед закрытием', exact: true })
	await expect(confirmation.getByRole('button', { name: 'Отмена', exact: true })).toBeFocused()
	await page.keyboard.press('Escape')
	await expect(confirmation).toHaveCount(0)
	await expect(close).toBeFocused()
	await expect(page.getByTestId('document-tab')).toHaveCount(1)
	await expect(page.getByText('Unsaved', { exact: true })).toBeVisible()
})
